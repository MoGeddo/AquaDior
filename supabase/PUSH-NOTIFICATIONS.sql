-- Additive external-push outbox for OneSignal.
-- Review and run on a backed-up STAGING project first. This file has NOT been
-- applied to the live Supabase project. It assumes public.notifications and
-- public.profiles already exist with UUID primary keys.

begin;

do $$
begin
  if to_regclass('public.notifications') is null then
    raise exception 'public.notifications is missing; stop and inspect the target project before continuing';
  end if;
  if to_regclass('public.profiles') is null then
    raise exception 'public.profiles is missing; stop and inspect the target project before continuing';
  end if;
end;
$$;

create table if not exists public.push_delivery_queue (
  id bigint generated by default as identity primary key,
  notification_id uuid not null unique
    references public.notifications(id) on delete cascade,
  user_id uuid not null
    references public.profiles(id) on delete cascade,
  status text not null default 'pending'
    check (status in ('pending', 'processing', 'sent', 'failed')),
  attempts smallint not null default 0 check (attempts >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  next_attempt_at timestamptz not null default now(),
  locked_at timestamptz,
  sent_at timestamptz,
  last_error text
);

create index if not exists idx_push_delivery_queue_due
  on public.push_delivery_queue(status, next_attempt_at, created_at)
  where status in ('pending', 'processing');

alter table public.push_delivery_queue enable row level security;
revoke all on table public.push_delivery_queue from public, anon, authenticated;

-- Queue each user-facing in-app notification in the same transaction.
create or replace function public.enqueue_external_push()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
begin
  if new.user_id is not null then
    insert into public.push_delivery_queue(notification_id, user_id)
    values (new.id, new.user_id)
    on conflict (notification_id) do nothing;
  end if;
  return new;
end;
$$;

revoke all on function public.enqueue_external_push() from public, anon, authenticated;

drop trigger if exists trg_enqueue_external_push on public.notifications;
create trigger trg_enqueue_external_push
after insert on public.notifications
for each row execute function public.enqueue_external_push();

-- Claim due rows transactionally so two overlapping cron invocations cannot
-- send the same queue item at the same time. Stale claims are recoverable.
create or replace function public.claim_push_deliveries(p_limit integer default 50)
returns table (
  queue_id bigint,
  notification_id uuid,
  user_id uuid,
  attempts integer
)
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
begin
  delete from public.push_delivery_queue
   where status in ('sent', 'failed')
     and updated_at < now() - interval '30 days';

  return query
  with candidates as (
    select q.id
    from public.push_delivery_queue as q
    where (q.status = 'pending' and q.next_attempt_at <= now())
       or (q.status = 'processing' and q.locked_at < now() - interval '5 minutes')
    order by q.created_at, q.id
    limit greatest(1, least(coalesce(p_limit, 50), 100))
    for update skip locked
  )
  update public.push_delivery_queue as q
     set status = 'processing',
         attempts = q.attempts + 1,
         locked_at = now(),
         updated_at = now()
    from candidates as c
   where q.id = c.id
  returning q.id, q.notification_id, q.user_id, q.attempts::integer;
end;
$$;

create or replace function public.complete_push_delivery(
  p_queue_id bigint,
  p_success boolean,
  p_error text default null
)
returns void
language sql
security definer
set search_path = pg_catalog, public
as $$
  update public.push_delivery_queue as q
     set status = case
           when p_success then 'sent'
           when q.attempts >= 5 then 'failed'
           else 'pending'
         end,
         sent_at = case when p_success then now() else null end,
         next_attempt_at = case
           when not p_success and q.attempts < 5 then now() + interval '1 minute'
           else q.next_attempt_at
         end,
         last_error = case when p_success then null else left(coalesce(p_error, 'Push delivery failed'), 500) end,
         locked_at = null,
         updated_at = now()
   where q.id = p_queue_id
     and q.status = 'processing';
$$;

revoke all on function public.claim_push_deliveries(integer) from public, anon, authenticated;
revoke all on function public.complete_push_delivery(bigint, boolean, text) from public, anon, authenticated;
grant execute on function public.claim_push_deliveries(integer) to service_role;
grant execute on function public.complete_push_delivery(bigint, boolean, text) to service_role;

commit;
